import type { ReactNode } from "react";
import { cn } from "@/lib/utils";
import { titleCase } from "@/lib/format";
import type { AlertStatus, IncidentStatus, Origin, Severity } from "@/lib/types";

const SEV_STYLE: Record<Severity, { dot: string; box: string }> = {
  critical: { dot: "bg-sev-critical", box: "border-sev-critical/50 bg-sev-critical/10" },
  high: { dot: "bg-sev-high", box: "border-sev-high/50 bg-sev-high/10" },
  medium: { dot: "bg-sev-medium", box: "border-sev-medium/50 bg-sev-medium/10" },
  low: { dot: "bg-sev-low", box: "border-sev-low/50 bg-sev-low/10" },
  info: { dot: "bg-sev-info", box: "border-sev-info/40 bg-sev-info/10" },
};

export const SEV_BAR: Record<Severity, string> = {
  critical: "bg-sev-critical",
  high: "bg-sev-high",
  medium: "bg-sev-medium",
  low: "bg-sev-low",
  info: "bg-sev-info",
};

/** Severity is always a coloured dot AND a text label, never colour alone. */
export function SeverityBadge({ severity }: { severity: Severity }) {
  const style = SEV_STYLE[severity] ?? SEV_STYLE.info;
  return (
    <span className={cn("inline-flex items-center gap-1.5 rounded border px-2 py-0.5 text-xs font-medium text-ink", style.box)}>
      <span className={cn("h-2 w-2 rounded-full", style.dot)} />
      {titleCase(severity)}
    </span>
  );
}

export function OriginBadge({ origin }: { origin: Origin }) {
  if (origin !== "simulated") return null;
  return (
    <span
      title="Simulated data generated by the built-in test simulator. This is not a real attack."
      className="inline-flex items-center rounded border border-sim/50 bg-sim/10 px-1.5 py-0.5 text-[11px] font-semibold text-ink"
    >
      SIM
    </span>
  );
}

const STATUS_STYLE: Record<string, string> = {
  open: "border-ink-3/50 text-ink",
  acknowledged: "border-sev-low/50 bg-sev-low/10 text-ink",
  investigating: "border-sev-low/50 bg-sev-low/10 text-ink",
  contained: "border-sev-medium/50 bg-sev-medium/10 text-ink",
  resolved: "border-good/50 bg-good/10 text-ink",
  closed: "border-line text-ink-2",
  false_positive: "border-line text-ink-2",
};

export function StatusChip({ status }: { status: AlertStatus | IncidentStatus }) {
  return (
    <span className={cn("inline-flex rounded border px-2 py-0.5 text-xs", STATUS_STYLE[status] ?? "border-line text-ink-2")}>
      {titleCase(status)}
    </span>
  );
}

export function RiskMeter({ score }: { score: number }) {
  const tone = score >= 85 ? "bg-sev-critical" : score >= 65 ? "bg-sev-high" : score >= 40 ? "bg-sev-medium" : "bg-sev-low";
  return (
    <div className="flex items-center gap-2" title={`Risk score ${score} out of 100`}>
      <div className="h-1.5 w-14 overflow-hidden rounded-full bg-raised">
        <div className={cn("h-full rounded-full", tone)} style={{ width: `${Math.max(4, Math.min(100, score))}%` }} />
      </div>
      <span className="num w-6 text-xs text-ink-2">{score}</span>
    </div>
  );
}

export function Mono({ children, className }: { children: ReactNode; className?: string }) {
  return <span className={cn("font-mono text-[13px]", className)}>{children}</span>;
}
